-- C LAB · Supabase schema
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  display_name text,
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.lessons (
  id text primary key,
  slug text unique not null,
  chapter text,
  title text not null,
  summary text,
  content_md text,
  starter_code text,
  expected_output text,
  stdin text,
  challenge_md text,
  order_index int not null default 99,
  is_published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.questions (
  id text primary key,
  lesson_id text references public.lessons(id) on delete cascade,
  type text not null default 'mcq',
  prompt_md text not null,
  choices jsonb not null default '[]'::jsonb,
  answer jsonb,
  explanation_md text,
  order_index int not null default 0
);

create table if not exists public.progress (
  user_id uuid references public.profiles(id) on delete cascade,
  lesson_id text references public.lessons(id) on delete cascade,
  status text not null default 'in_progress',
  code text,
  updated_at timestamptz not null default now(),
  primary key (user_id, lesson_id)
);

create table if not exists public.settings (
  key text primary key,
  value jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.chat_messages (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  lesson_id text,
  role text not null,
  content text not null,
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email, display_name, role)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'display_name', split_part(new.email,'@',1)), 'student')
  on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.lessons enable row level security;
alter table public.questions enable row level security;
alter table public.progress enable row level security;
alter table public.settings enable row level security;
alter table public.chat_messages enable row level security;

drop policy if exists "profiles self read" on public.profiles;
create policy "profiles self read" on public.profiles for select using (auth.uid() = id);
drop policy if exists "profiles self update" on public.profiles;
create policy "profiles self update" on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "published lessons read" on public.lessons;
create policy "published lessons read" on public.lessons for select using (is_published = true);
drop policy if exists "published questions read" on public.questions;
create policy "published questions read" on public.questions for select using (true);
drop policy if exists "progress own" on public.progress;
create policy "progress own" on public.progress for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
drop policy if exists "chat own" on public.chat_messages;
create policy "chat own" on public.chat_messages for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

